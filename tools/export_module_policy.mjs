// Trusted deployment metadata, never submitted by a browser. Node 24 strips TS types.
import { readdir } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import path from 'node:path';
export async function modulePolicies(root = 'artifacts/y-hub/src/modules') {
 const modules=[];
 for(const entry of (await readdir(root,{withFileTypes:true})).sort((a,b)=>a.name.localeCompare(b.name))){
  if(!entry.isDirectory() || entry.name.startsWith('__'))continue;
  const filename=path.resolve(root,entry.name,'module.ts');
  const {default:m}=await import(pathToFileURL(filename).href);
  if(m.defaultEnabled===false)continue;
  if(m.apiVersion!==2)throw new Error('Unsupported module policy API');
  modules.push({id:m.id,kind:m.kind,roles:m.access.roles,majors:m.access.majors??[],restricted:m.access.majorRestrictedRoles??m.access.roles,permissions:m.access.permissions??[],routes:m.routes.map(r=>({path:r.path,title:r.navigation?.title??r.dashboard?.title??m.title,icon:r.navigation?.iconId??r.dashboard?.iconId??'box',dashboardOrder:r.dashboard?.order??null}))});
 }
 return modules;
}
if(import.meta.url===pathToFileURL(path.resolve(process.argv[1]??'')).href){
 const rows=await modulePolicies();
 const quote=s=>"'"+s.replaceAll("'","''")+"'";
 process.stdout.write('-- Generated by node tools/export_module_policy.mjs; review/apply as deployment metadata only.\n');
 for(const m of rows)process.stdout.write(`INSERT INTO public.module_policies(id,kind,roles,majors,restricted_roles,permissions,routes) VALUES (${quote(m.id)},${quote(m.kind)},ARRAY[${m.roles.map(quote)}]::text[],ARRAY[${m.majors.map(quote)}]::text[],ARRAY[${m.restricted.map(quote)}]::text[],ARRAY[${m.permissions.map(quote)}]::text[],${quote(JSON.stringify(m.routes))}::jsonb) ON CONFLICT(id) DO UPDATE SET kind=EXCLUDED.kind,roles=EXCLUDED.roles,majors=EXCLUDED.majors,restricted_roles=EXCLUDED.restricted_roles,permissions=EXCLUDED.permissions,routes=EXCLUDED.routes;\n`);
}
