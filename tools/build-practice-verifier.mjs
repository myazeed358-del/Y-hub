// A reproducible server artifact of the existing mathematical engine. No forked algorithm.
import { createRequire } from "node:module";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
const root = new URL("../", import.meta.url);
const requireApp = createRequire(new URL("artifacts/y-hub/package.json", root));
const requireVite = createRequire(requireApp.resolve("vite"));
const { build } = requireVite("esbuild");
const result = await build({
  entryPoints: [
    fileURLToPath(
      new URL(
        "artifacts/y-hub/src/services/practice-math/polynomialDerivative.ts",
        root,
      ),
    ),
  ],
  bundle: true,
  write: false,
  platform: "neutral",
  format: "esm",
  target: "es2022",
  minify: true,
  legalComments: "inline",
  logLevel: "silent",
  absWorkingDir: fileURLToPath(root),
});
const content =
  "// Generated by tools/build-practice-verifier.mjs from the existing math engine. Do not edit.\n" +
  result.outputFiles[0].text;
const output = new URL(
  "artifacts/y-hub/supabase/functions/_shared/tutor/polynomialVerifier.mjs",
  root,
);
if (process.argv.includes("--check")) {
  if ((await readFile(output, "utf8")) !== content)
    throw new Error("Server math bundle is stale; regenerate and verify it");
  console.log("PASS: server math artifact matches source");
} else await writeFile(output, content);
